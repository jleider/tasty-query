package simple_trees

/* dotc erases a `Unit` result to `void` (signature `scala.Unit`) only when the result type is `Unit` or an alias of it,
 * as seen from its prefix. A result whose type is only bounded by `Unit`, a singleton type, or an opaque alias of
 * `Unit` seen from outside its scope, erases to `scala.runtime.BoxedUnit`.
 */

object UnitErasureOpaque:
  opaque type Phantom[+A] = Unit

  // Inside its scope, the opaque type alias is transparent
  def inside[A]: Phantom[A] = ()
end UnitErasureOpaque

trait UnitErasureHasElem:
  type Elem

object UnitErasureLib:
  type U = Unit

object UnitErasureExports:
  export UnitErasureLib.U

abstract class UnitErasureNonAlias:
  type UnitAlias = Unit
  type AbstractUnit <: Unit

  def aliasResult(): UnitAlias = ()

  def abstractResult(): AbstractUnit

  def typeParamResult[T <: Unit](t: T): T = t

  def hkTypeParamResult[F[x] <: Unit](): F[Int]

  def opaqueResult[A](p: UnitErasureOpaque.Phantom[A]): UnitErasureOpaque.Phantom[A] = p

  def singletonResult(u: Unit): u.type = u

  // Aliases as seen from the prefix: a refinement, and the alias generated by an `export`
  def refinedAliasResult(c: UnitErasureHasElem { type Elem = Unit }): c.Elem

  def refinedBoundedResult(c: UnitErasureHasElem { type Elem <: Unit }): c.Elem

  def exportedAliasResult(): UnitErasureExports.U

  def calls(c: UnitErasureHasElem { type Elem = Unit }, d: UnitErasureHasElem { type Elem <: Unit }): Unit =
    aliasResult()
    abstractResult()
    typeParamResult(())
    hkTypeParamResult[[x] =>> Unit]()
    opaqueResult(UnitErasureOpaque.inside[Int])
    singletonResult(())
    refinedAliasResult(c)
    refinedBoundedResult(d)
    exportedAliasResult()
  end calls
end UnitErasureNonAlias
